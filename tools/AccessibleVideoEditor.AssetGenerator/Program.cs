using AccessibleVideoEditor.Core.Input;
using AccessibleVideoEditor.Core.Sound;

// Writes the built-in sounds and default keymap for the installer, or the keyboard documents.
// Usage: AccessibleVideoEditor.AssetGenerator <output folder>
//        AccessibleVideoEditor.AssetGenerator --docs <docs folder>
if (args.Length == 2 && args[0] == "--docs")
{
    var docs = Path.GetFullPath(args[1]);
    Directory.CreateDirectory(docs);
    var keymap = Keymap.Default();
    File.WriteAllText(Path.Combine(docs, "KEYBOARD.md"), KeyboardReference.Markdown(keymap));
    File.WriteAllText(Path.Combine(docs, "KEYBOARD.html"), KeyboardReference.Html(keymap));
    Console.WriteLine($"Wrote KEYBOARD.md and KEYBOARD.html to {docs}");
    return 0;
}

if (args.Length != 1)
{
    Console.Error.WriteLine("Usage: AccessibleVideoEditor.AssetGenerator <output folder>");
    Console.Error.WriteLine("       AccessibleVideoEditor.AssetGenerator --docs <docs folder>");
    return 2;
}

var root = Path.GetFullPath(args[0]);
var effects = Path.Combine(root, "Sounds", "Effects");
SoundEffects.WriteAll(effects, overwrite: true);
Console.WriteLine($"Wrote {SoundEffects.BuiltIn.Count} sound effects to {effects}");

foreach (var theme in EarconTheme.BuiltIn.Where(t => t.Name != "Off"))
{
    var folder = Path.Combine(root, "Sounds", "Themes", theme.Name);
    theme.Export(folder);
    Console.WriteLine($"Wrote theme {theme.Name} to {folder}");
}

File.WriteAllText(Path.Combine(root, "Sounds", "LICENSE.txt"),
    """
    The sounds in this folder were generated by ClipScribe's built-in synthesizer.
    They contain no recordings or samples from anyone else.

    They are dedicated to the public domain (CC0 1.0 Universal):
    https://creativecommons.org/publicdomain/zero/1.0/
    You may use them in any video, including commercial videos, without credit.
    """);

Keymap.Default().Save(Path.Combine(root, "default-keymap.json"));
Console.WriteLine("Wrote default-keymap.json");
return 0;
